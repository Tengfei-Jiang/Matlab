function build_mmc_ad(scheme)
%BUILD_MMC_AD  在 MMC-VSG 副本模型上插入 J-D 自适应律
%
%   build_mmc_ad(5)   % 本文方案
%   build_mmc_ad(1)   % 固定参数基准
%
%   只改副本 MMC_30_VSG_AD.slx，不动原始 MMC_30_VSG.slx。
%
%   与论文理想源算例的差别：本模型的摇摆方程写作
%       J*dw/dt = [(P_ref - kf*dw - P_e)/w0] - D*dw
%   即功率先除 w0 变转矩，故等效惯量为 Jp = J*w0。自适应律内部
%   按论文口径算 Jp、Dp，输出前除以 w0 转成模型量纲。

if nargin < 1, scheme = 5; end

d      = 'C:/Users/Lenovo/WorkBuddy/2026-09-18-17-03-29/git/mmc_vsg';
mdlName = 'MMC_30_VSG_AD';
cd(d); addpath(d);
fid = fopen([d '/build_ad.log'], 'w', 'n', 'UTF-8');

try
    % ---------------- 1. 标定参数 ----------------
    w0   = 2*pi*50;
    Up   = 5470.0;                      % PCC 相电压峰值 V（实测）
    Xeq  = 0.02033*w0;                  % 等效电抗 ohm
    Kd   = 3*Up*Up/Xeq;                 % 同步功率系数 W/rad
    lam  = 10.0;  z0 = 0.707;  zmax = 1.0;
    wn0  = lam/z0;
    Jp0  = Kd/wn0^2;                    % 论文口径惯量
    Dp0  = 2*z0*sqrt(Kd*Jp0);           % 论文口径总阻尼
    J0   = Jp0/w0;                      % 模型量纲
    DS0  = Dp0/w0;

    P = struct();
    P.w0=w0; P.Kd=Kd; P.lam=lam; P.z0=z0; P.zmax=zmax; P.wn0=wn0;
    P.J0=J0; P.DS0=DS0;
    P.Jmin=0.30*J0; P.Jmax=2.00*J0;
    P.Dmin=0.30*DS0; P.Dmax=2.20*DS0;
    P.muJ = 13.0*J0;                    % 惯量变化率上限（与论文 muJ/J0 同比例）
    P.nu=0.15; P.nb=0.55; P.dzr=0.50; P.dzd=0.00;
    P.tau=0.02; P.db=0.02; P.kpsi=14.0; P.txi=0.04;
    P.lam_floor=1; P.scheme=scheme; P.Ts=2e-4;
    P.qref=0.03;   P.dfref=0.064; P.dwref=0.40; P.dref=4.0;
    P.kf=8.5;
    P.delta0 = asin(1e6/Kd);   % 初始功角：由 Pref=1 MW 直接起于工作点

    fn = fieldnames(P);
    for k = 1:numel(fn), assignin('base', fn{k}, P.(fn{k})); end

    fprintf(fid, 'Kd = %.4e W/rad\n', Kd);
    fprintf(fid, 'J0(model) = %.4f  -> Jp0 = %.4e\n', J0, Jp0);
    fprintf(fid, 'D0(model) = %.4f  -> Dp0 = %.4e\n', DS0, Dp0);
    fprintf(fid, 'lam = D/(2J) = %.3f\n', DS0/(2*J0));

    % ---------------- 2. 加载副本 ----------------
    load_system([d '/' mdlName '.slx']);

    % ---------------- 3. 改写 InitFcn ----------------
    initStr = sprintf([ ...
        'Rf=0.5929;\n' ...
        'fn=50;\n' ...
        'w0=2*pi*fn;\n' ...
        'Lf=0.5*0.0135+0.01358;\n' ...
        'R=0.5;\n' ...
        'kf=%g;\n' ...
        '%% ---- MMC 平台指标层标定（6.6 kV / 1 MVA，Up=5470 V）----\n' ...
        'Kd=%g;\n' ...
        'lam=%g; z0=%g; zmax=%g; wn0=lam/z0;\n' ...
        'J0=%g; DS0=%g;\n' ...
        'Jmin=0.3*J0; Jmax=2.0*J0; Dmin=0.3*DS0; Dmax=2.2*DS0;\n' ...
        'muJ=%g;\n' ...
        'nu=%g; nb=%g; dzr=%g; dzd=%g;\n' ...
        'tau=%g; db=%g; kpsi=%g; txi=%g;\n' ...
        'Ts=%g; qref=%g; dfref=%g; dwref=%g; dref=%g;\n' ...
        'lam_floor=%d; scheme=%d;\n' ...
        'delta0=%g;\n' ...
        'J=J0; D=DS0;\n'], ...
        P.kf, Kd, lam, z0, zmax, J0, DS0, P.muJ, ...
        P.nu, P.nb, P.dzr, P.dzd, P.tau, P.db, P.kpsi, P.txi, ...
        P.Ts, P.qref, P.dfref, P.dwref, P.dref, P.lam_floor, scheme, P.delta0);
    set_param(mdlName, 'InitFcn', initStr);
    fprintf(fid, 'InitFcn 已更新（%d 字符）\n', numel(initStr));

    % ---------------- 4. Pref 改为阶跃 ----------------
    if getSimulinkBlockHandle([mdlName '/Constant3']) > 0
        if ~strcmp(get_param([mdlName '/Constant3'], 'BlockType'), 'Step')
            replace_block([mdlName '/Constant3'], 'Constant', ...
                'Step', 'noprompt');
        end
        set_param([mdlName '/Constant3'], 'Time', '1.3', ...
            'Before', '1e6', 'After', '1.1e6', 'SampleTime', '0');
        fprintf(fid, 'Pref 已改为阶跃：1.0 -> 1.1 MW @ 1.3 s\n');
    end

    % ---------------- 5. 有功环：替换两个增益 ----------------
    p = [mdlName '/VSG控制/VSG有功控制-频率调节-一次调频'];

    % Gain1 是 1/J，改为 Divide（Product 的 */ 形式）
    b1 = [p '/Gain1'];
    if getSimulinkBlockHandle(b1) > 0 && strcmp(get_param(b1,'BlockType'), 'Gain')
        replace_block(b1, 'Gain', 'built-in/Product', 'noprompt');
        set_param(b1, 'Inputs', '*/');
        fprintf(fid, 'Gain1(1/J) -> Divide\n');
    end

    % Gain2 是 D，改为 Product（dw * Dm）
    b2 = [p '/Gain2'];
    if getSimulinkBlockHandle(b2) > 0 && strcmp(get_param(b2,'BlockType'), 'Gain')
        replace_block(b2, 'Gain', 'built-in/Product', 'noprompt');
        set_param(b2, 'Inputs', '2');
        fprintf(fid, 'Gain2(D) -> Product\n');
    end

    % ---------------- 6. 插入自适应律 ----------------
    zoh = [p '/ZOH_dw'];
    if getSimulinkBlockHandle(zoh) < 0
        add_block('simulink/Discrete/Zero-Order Hold', zoh, ...
            'SampleTime', 'Ts', 'Position', [40 300 75 330]);
        add_line(p, 'Integrator/1', 'ZOH_dw/1');
    end

    adp = [p '/adap_law'];
    if getSimulinkBlockHandle(adp) < 0
        add_block('simulink/User-Defined Functions/MATLAB Function', adp, ...
            'Position', [110 280 260 380]);
        add_line(p, 'ZOH_dw/1', 'adap_law/1');
    end

    % 自适应律内部：判决量 -> 指标调度 -> 逆映射 -> 限幅
    code = [ ...
"function [Jm, Dm, wn_o, z_o, xi_o] = adap_law(dw)" newline ...
"% 闭环指标整形：与论文 §3.4 一致，量纲转换到模型侧（Jm = Jp/w0）" newline ...
"persistent dwf dwp ddwf xf first" newline ...
"if isempty(first)" newline ...
"    dwf = 0; dwp = 0; ddwf = 0; xf = 0; first = 1;" newline ...
"end" newline ...
"a = Ts/(tau + Ts);" newline ...
"dwf = dwf + a*(dw - dwf);                 % 量测低通" newline ...
"d1  = (dwf - dwp)/Ts;" newline ...
"dwp = dwf;" newline ...
"ddwf = ddwf + a*(d1 - ddwf);              % 滤波微分" newline ...
"xi = dwf*ddwf/max(qref, 1e-9);" newline ...
"if txi > 0" newline ...
"    xf = xf + (xi - xf)*Ts/txi;           % 判决量附加惯性" newline ...
"    xi = xf;" newline ...
"end" newline ...
"s  = (2/pi)*atan(kpsi*(xi - db*tanh(xi/db)));   % 软化死区" newline ...
"sp = max(s, 0);" newline ...
"sm = min(s, 0);" newline ...
"wn = wn0*(1 - nu*sp - nb*sm);" newline ...
"zs = z0 + dzd*sp - dzr*sm;" newline ...
"if lam_floor > 0" newline ...
"    zf = lam/wn;" newline ...
"else" newline ...
"    zf = z0;" newline ...
"end" newline ...
"z = min(max(max(zs, zf), z0), zmax);" newline ...
"Jp = Kd/wn^2;" newline ...
"Dp = 2*z*sqrt(Kd*Jp);" newline ...
"switch scheme" newline ...
"    case 1" newline ...
"        Jp = Kd/wn0^2;  Dp = 2*z0*sqrt(Kd*Jp);" newline ...
"    otherwise" newline ...
"end" newline ...
"Jm = Jp/w0;" newline ...
"Dm = Dp/w0;" newline ...
"Jm = min(max(Jm, Jmin), Jmax);" newline ...
"Dm = min(max(Dm, Dmin), Dmax);" newline ...
"wn_o = wn;  z_o = z;  xi_o = xi;" newline ...
"end" newline];

    rt = sfroot;
    ch = rt.find('-isa', 'Stateflow.EMChart', 'Path', adp);
    if isempty(ch), error('未定位 MATLAB Function：%s', adp); end
    ch.Script = char(strjoin(string(code(:)), newline));

    pnames = {'Ts','tau','qref','txi','kpsi','db','wn0','nu','nb','z0', ...
              'dzd','dzr','lam','zmax','Kd','lam_floor','scheme','Jmin', ...
              'Jmax','Dmin','Dmax','w0'};
    dn = ch.find('-isa', 'Stateflow.Data');
    have = arrayfun(@(x) x.Name, dn, 'UniformOutput', false);
    for k = 1:numel(pnames)
        if ~any(strcmp(have, pnames{k}))
            dd = Stateflow.Data(ch);
            dd.Name = pnames{k};
            dd.Scope = 'Parameter';
        end
    end
    fprintf(fid, '自适应律已写入，参数 %d 个\n', numel(pnames));

    % 功角积分器从稳态初值起步，消除启动爬升
    bth = [p '/Integrator1'];
    if getSimulinkBlockHandle(bth) > 0
        set_param(bth, 'InitialCondition', 'delta0');
        fprintf(fid, 'Integrator1 初值 -> delta0\n');
    end

    % ---------------- 7. J/D 接到 Divide / Product ----------------
    try, add_line(p, 'adap_law/1', 'Gain1/2'); catch, end   % Jm -> Divide 分母
    try, add_line(p, 'adap_law/2', 'Gain2/2'); catch, end   % Dm -> Product

    % ---------------- 8. 记录通道 ----------------
    recs = { ...
        [p '/RW'],     'omega_vsg', 'Sum4/1'; ...
        [p '/RPe'],    'Pe_vsg',    'Pe/1'; ...
        [p '/RJ'],     'J_vsg',     'adap_law/1'; ...
        [p '/RD'],     'D_vsg',     'adap_law/2'; ...
        [p '/RXi'],    'xi_vsg',    'adap_law/5'};
    for k = 1:size(recs, 1)
        if getSimulinkBlockHandle(recs{k,1}) < 0
            add_block('simulink/Sinks/To Workspace', recs{k,1}, ...
                'VariableName', recs{k,2}, 'SaveFormat', 'timeseries', ...
                'SampleTime', 'Ts', 'Position', [330 250+50*k 400 280+50*k]);
            bn = strrep(recs{k,1}, [p '/'], '');
            add_line(p, recs{k,3}, [bn '/1']);
        end
    end

    set_param(mdlName, 'StopTime', '2.4');
    save_system(mdlName, [d '/' mdlName '.slx']);
    fprintf(fid, 'BUILD OK\n');
catch ME
    fprintf(fid, 'ERR %s : %s\n', ME.identifier, ME.message);
    for k = 1:numel(ME.stack)
        fprintf(fid, '  at %s line %d\n', ME.stack(k).name, ME.stack(k).line);
    end
end
fclose(fid);
end
